import type { z } from 'zod';
import type { ContractEntry } from './registry.js';

/**
 * Zod → Swift emitter for the Contracts module (plan §3, M5 B1; rev 4.11 (5)).
 *
 * Mapping (the only shapes the contract uses; anything else throws so a new
 * Zod feature is a deliberate generator change):
 * - object → `public struct … : Codable, Hashable, Sendable` with a public
 *   memberwise init and explicit `CodingKeys` when a key is not already a
 *   Swift property name (snake_case view columns);
 * - string enum → `public enum … : Codable, Hashable, Sendable` with one case
 *   per entry **plus `case unknown(String)`**, so the app keeps decoding when
 *   the backend adds a league, a period type, a status or a change type;
 *   an entry literally named `unknown` folds into that case;
 * - discriminated union → a struct of the fields every variant shares (the
 *   envelope of a change, the base of a play) plus `type: Kind`, where `Kind`
 *   is an enum with one case per variant (payload = the variant's own fields)
 *   **plus `case unknown(String)`** carrying the raw discriminator: a client
 *   still reads `seq` and the period of a change or play it does not know;
 * - nullable / optional → `T?`; array → `[T]`; `record(string, unknown)` →
 *   `[String: JSONValue]`; `unknown` → `JSONValue`; int → `Int`; number →
 *   `Double`; string (incl. uuid, ISO datetime) → `String` (WehoopData maps
 *   ids and timestamps once); literal → its primitive type.
 * - a schema that is a registry root is referenced by its registered name
 *   (object identity); an anonymous nested object or enum becomes a nested
 *   type of its parent, named after the property (singular for arrays).
 *
 * The output is deterministic (registry order, shape order) so that
 * `pnpm gen:swift --check` can compare bytes.
 */

// biome-ignore lint/suspicious/noExplicitAny: Zod's internal def is untyped on purpose; every read is narrowed below.
