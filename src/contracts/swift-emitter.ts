const HEADER = `// Generated by wehoop-api \`pnpm gen:swift\` from src/contracts/registry.ts. DO NOT EDIT.
// Regenerate into the app: pnpm gen:swift --out <Wehoop>/WehoopKit/Sources/Contracts/Generated
// Verify (CI):            pnpm gen:swift --check [--out <dir>]
`;

const JSON_VALUE_FILE = `${HEADER}
/// Any JSON value: the type of \`extra\`, \`venue\`, \`records\` and every other
/// untyped column the backend passes through.
public enum JSONValue: Codable, Hashable, Sendable {
    case null
    case bool(Bool)
    case number(Double)
    case string(String)
    case array([JSONValue])
    case object([String: JSONValue])

    public init(from decoder: any Decoder) throws {
        let container = try decoder.singleValueContainer()
        if container.decodeNil() {
            self = .null
        } else if let value = try? container.decode(Bool.self) {
            self = .bool(value)
        } else if let value = try? container.decode(Double.self) {
            self = .number(value)
        } else if let value = try? container.decode(String.self) {
            self = .string(value)
        } else if let value = try? container.decode([JSONValue].self) {
            self = .array(value)
        } else if let value = try? container.decode([String: JSONValue].self) {
            self = .object(value)
        } else {
            throw DecodingError.typeMismatch(
                JSONValue.self,
                DecodingError.Context(codingPath: decoder.codingPath, debugDescription: "Not a JSON value")
            )
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.singleValueContainer()
        switch self {
        case .null: try container.encodeNil()
        case .bool(let value): try container.encode(value)
        case .number(let value): try container.encode(value)
        case .string(let value): try container.encode(value)
        case .array(let value): try container.encode(value)
        case .object(let value): try container.encode(value)
        }
    }
}
`;

function def(schema: z.ZodType): Def {
  return (schema as unknown as { _zod: { def: Def } })._zod.def;
}

export function camelCase(raw: string): string {
  const parts = raw
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((p) => p.toLowerCase());
  return parts.map((p, i) => (i === 0 ? p : p[0]?.toUpperCase() + p.slice(1))).join('');
}

export function pascalCase(raw: string): string {
  const c = camelCase(raw);
  return c[0]?.toUpperCase() + c.slice(1);
}

function identifier(name: string): string {
  return SWIFT_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

function singular(name: string): string {
  return name.endsWith('s') && !name.endsWith('ss') ? name.slice(0, -1) : name;
}

function indentLines(text: string, level: number): string {
  const pad = '    '.repeat(level);
  return text
    .split('\n')
    .map((l) => (l.length ? pad + l : l))
    .join('\n');
}

interface Field {
  key: string;
  name: string;
  type: string;
}

interface Scope {
  /** Nested declarations collected while resolving the fields of one type. */
  nested: string[];
  nestedNames: Set<string>;
  /** The root being emitted; a reference to it is not replaced by a name (no recursion exists in the contract). */
  root: z.ZodType;
  /** The direct scope of a tagged union declares `Kind` itself. */
  reservesKind?: boolean;
}

export class SwiftEmitter {
  private readonly rootNames = new Map<z.ZodType, string>();
  private readonly names = new Set<string>();

  constructor(private readonly entries: readonly ContractEntry[]) {
    for (const e of entries) {
      if (this.names.has(e.name)) throw new Error(`duplicate contract name ${e.name}`);
      if (this.rootNames.has(e.schema)) throw new Error(`schema registered twice (${e.name})`);
      this.rootNames.set(e.schema, e.name);
      this.names.add(e.name);
    }
  }

  /** File name (without directory) → Swift source. */
  emit(): Map<string, string> {
    const byFile = new Map<string, string[]>();
    for (const e of this.entries) {
      const list = byFile.get(`${e.file}.swift`) ?? [];
      list.push(this.emitRoot(e));
      byFile.set(`${e.file}.swift`, list);
    }
    const out = new Map<string, string>();
    out.set('JSONValue.swift', JSON_VALUE_FILE);
    for (const [file, decls] of byFile) out.set(file, `${HEADER}\n${decls.join('\n')}`);
    return out;
  }

  private emitRoot(e: ContractEntry): string {
    const d = def(e.schema);
    const doc = `/// ${e.doc}`;
    switch (d.type) {
      case 'enum':
        return `${doc}\n${this.stringEnum(e.name, Object.values(d.entries) as string[])}`;
      case 'object':
        return `${doc}\n${this.struct(e.name, d.shape, e.schema)}`;
      case 'union':
        if (!d.discriminator) throw new Error(`${e.name}: only discriminated unions are supported`);
        return `${doc}\n${this.taggedUnion(e.name, d.discriminator, d.options, e.schema)}`;
      default:
        throw new Error(`${e.name}: unsupported root schema type ${d.type}`);
    }
  }

  private stringEnum(name: string, entries: string[]): string {
    const known = entries.filter((v) => v !== 'unknown');
    const cases = known.map((v) => `    case ${identifier(camelCase(v))}`).join('\n');
    const toRaw = known.map((v) => `        case .${identifier(camelCase(v))}: "${v}"`).join('\n');
    const fromRaw = known
      .map((v) => `        case "${v}": self = .${identifier(camelCase(v))}`)
      .join('\n');
    const knownItems = known.map((v) => `.${identifier(camelCase(v))}`);
    const knownOneLine = knownItems.join(', ');
    const knownList =
      knownOneLine.length <= 60
        ? knownOneLine
        : `\n${knownItems.map((k) => `        ${k},`).join('\n')}\n    `;
    const foldNote = entries.includes('unknown')
      ? `\n    /// The backend's own \`unknown\` entry decodes as \`.unknown("unknown")\`.`
      : '';
    return `public enum ${name}: Codable, Hashable, Sendable {
${cases}
    /// A value this build does not know (plan rev 4.11 (5)): kept and shown as such, never dropped.${foldNote}
    case unknown(String)

    /// Every value this build knows, in backend order.
    public static let known: [${name}] = [${knownList}]

    public init(rawValue: String) {
        switch rawValue {
${fromRaw}
        default: self = .unknown(rawValue)
        }
    }

    public var rawValue: String {
        switch self {
${toRaw}
        case .unknown(let raw): raw
        }
    }

    public init(from decoder: any Decoder) throws {
        self.init(rawValue: try decoder.singleValueContainer().decode(String.self))
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.singleValueContainer()
        try container.encode(rawValue)
    }
}
`;
  }

  private fields(shape: Record<string, z.ZodType>, scope: Scope): Field[] {
    return Object.entries(shape).map(([key, schema]) => ({
      key,
      name: camelCase(key),
      type: this.typeOf(schema, key, scope),
    }));
  }

  private struct(name: string, shape: Record<string, z.ZodType>, root: z.ZodType): string {
    const scope: Scope = { nested: [], nestedNames: new Set(), root };
    const fields = this.fields(shape, scope);
    return this.structSource(name, fields, scope, []);
  }

  private structSource(
    name: string,
    fields: Field[],
    scope: Scope,
    extraMembers: string[],
  ): string {
    const lets = fields.map((f) => `    public let ${identifier(f.name)}: ${f.type}`).join('\n');
    const params = fields.map((f) => `${identifier(f.name)}: ${f.type}`);
    const oneLine = `    public init(${params.join(', ')}) {`;
    const initHead =
      oneLine.length <= 100
        ? oneLine
        : `    public init(\n${params.map((p) => `        ${p}`).join(',\n')}\n    ) {`;
    const initBody = fields
      .map((f) => `        self.${identifier(f.name)} = ${identifier(f.name)}`)
      .join('\n');
    const members: string[] = [];
    members.push(`${lets}\n\n${initHead}\n${initBody}\n    }`);
    if (fields.some((f) => f.key !== f.name)) members.push(this.codingKeys(fields));
    members.push(...extraMembers);
    members.push(...scope.nested.map((n) => indentLines(n, 1).replace(/\s+$/, '')));
    return `public struct ${name}: Codable, Hashable, Sendable {\n${members.join('\n\n')}\n}\n`;
  }

  private codingKeys(fields: Field[]): string {
    const cases = fields
      .map((f) =>
        f.key === f.name
          ? `        case ${identifier(f.name)}`
          : `        case ${identifier(f.name)} = "${f.key}"`,
      )
      .join('\n');
    return `    private enum CodingKeys: String, CodingKey {\n${cases}\n    }`;
  }

  private taggedUnion(
    name: string,
    discriminator: string,
    options: z.ZodType[],
    root: z.ZodType,
  ): string {
    const shapes = options.map((o) => {
      const d = def(o);
      if (d.type !== 'object') throw new Error(`${name}: union option is not an object`);
      return d.shape as Record<string, z.ZodType>;
    });
    const first = shapes[0];
    if (!first) throw new Error(`${name}: empty union`);
    // Shared = same key bound to the same Zod object in every variant (the spread base).
    const sharedKeys = Object.keys(first).filter(
      (k) => k !== discriminator && shapes.every((s) => s[k] === first[k]),
    );
    const scope: Scope = { nested: [], nestedNames: new Set(), root, reservesKind: true };
    const shared = this.fields(
      Object.fromEntries(sharedKeys.map((k) => [k, first[k] as z.ZodType])),
      scope,
    );
    const variants = shapes.map((s) => {
      const tag = def(s[discriminator] as z.ZodType);
      if (tag.type !== 'literal' || typeof tag.values[0] !== 'string') {
        throw new Error(`${name}: discriminator must be a string literal`);
      }
      const raw = tag.values[0] as string;
      const own = Object.fromEntries(
        Object.entries(s).filter(([k]) => k !== discriminator && !sharedKeys.includes(k)),
      );
      let structName = pascalCase(raw);
      if (this.names.has(structName) || structName === 'Kind') structName = `${structName}Payload`;
      const caseName = camelCase(raw);
      if (Object.keys(own).length === 0) return { raw, caseName, structName: null };
      this.declareNested(scope, structName);
      const inner: Scope = { nested: [], nestedNames: new Set(), root };
      const fields = this.fields(own, inner);
      scope.nested.push(this.structSource(structName, fields, inner, []));
      return { raw, caseName, structName };
    });

    const kindCases = variants
      .map((v) =>
        v.structName
          ? `        case ${identifier(v.caseName)}(${v.structName})`
          : `        case ${identifier(v.caseName)}`,
      )
      .join('\n');
    const kindRaw = variants
      .map((v) => `            case .${identifier(v.caseName)}: "${v.raw}"`)
      .join('\n');
    const decode = variants
      .map((v) =>
        v.structName
          ? `        case "${v.raw}": type = .${identifier(v.caseName)}(try ${v.structName}(from: decoder))`
          : `        case "${v.raw}": type = .${identifier(v.caseName)}`,
      )
      .join('\n');
    const encodePayload = variants
      .filter((v) => v.structName)
      .map(
        (v) =>
          `        case .${identifier(v.caseName)}(let payload): try payload.encode(to: encoder)`,
      )
      .join('\n');
    const noPayload = [
      ...variants.filter((v) => !v.structName).map((v) => `.${identifier(v.caseName)}`),
      '.unknown',
    ];
    // Optional shared fields: absent and null both decode to nil, nil is omitted on encode
    // (what the synthesized Codable of a plain struct does).
    const sharedDecode = shared
      .map((f) =>
        f.type.endsWith('?')
          ? `        ${identifier(f.name)} = try container.decodeIfPresent(${f.type.slice(0, -1)}.self, forKey: .${identifier(f.name)})`
          : `        ${identifier(f.name)} = try container.decode(${f.type}.self, forKey: .${identifier(f.name)})`,
      )
      .join('\n');
    const sharedEncode = shared
      .map((f) =>
        f.type.endsWith('?')
          ? `        try container.encodeIfPresent(${identifier(f.name)}, forKey: .${identifier(f.name)})`
          : `        try container.encode(${identifier(f.name)}, forKey: .${identifier(f.name)})`,
      )
      .join('\n');
    const kind = `    /// The variant, by the wire \`${discriminator}\`.
    public enum Kind: Hashable, Sendable {
${kindCases}
        /// A \`${discriminator}\` this build does not know (plan rev 4.11 (5)): the shared fields are
        /// still decoded, the variant's own fields are not.
        case unknown(String)

        public var rawValue: String {
            switch self {
${kindRaw}
            case .unknown(let raw): raw
            }
        }
    }`;
    const codable = `    public init(from decoder: any Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
${sharedDecode}
        let raw = try container.decode(String.self, forKey: .${identifier(discriminator)})
        switch raw {
${decode}
        default: type = .unknown(raw)
        }
    }

    public func encode(to encoder: any Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
${sharedEncode}
        try container.encode(type.rawValue, forKey: .${identifier(discriminator)})
        switch type {
${encodePayload}
        case ${noPayload.join(', ')}: break
        }
    }`;
    const typeField: Field = { key: discriminator, name: camelCase(discriminator), type: 'Kind' };
    const allFields = [...shared, typeField];
    // CodingKeys are always needed here (custom Codable).
    const members = [this.codingKeys(allFields), kind, codable];
    return this.structSource(name, allFields, scope, members);
  }

  private declareNested(scope: Scope, name: string): void {
    if (scope.nestedNames.has(name))
      throw new Error(`nested type ${name} declared twice in one scope`);
    scope.nestedNames.add(name);
  }

  private nestedName(scope: Scope, key: string, isElement: boolean): string {
    let name = pascalCase(isElement ? singular(key) : key);
    if (this.names.has(name) || (scope.reservesKind && name === 'Kind')) name = `${name}Payload`;
    this.declareNested(scope, name);
    return name;
  }

  private typeOf(schema: z.ZodType, key: string, scope: Scope, isElement = false): string {
    const rootName = this.rootNames.get(schema);
    if (rootName && schema !== scope.root) return rootName;
    const d = def(schema);
    switch (d.type) {
      case 'string':
        return 'String';
      case 'number':
        return d.format === 'safeint' ? 'Int' : 'Double';
      case 'boolean':
        return 'Bool';
      case 'literal': {
        const v = d.values[0];
        if (typeof v === 'string') return 'String';
        if (typeof v === 'boolean') return 'Bool';
        if (typeof v === 'number') return Number.isInteger(v) ? 'Int' : 'Double';
        throw new Error(`${key}: unsupported literal ${String(v)}`);
      }
      case 'nullable':
      case 'optional': {
        const inner = this.typeOf(d.innerType, key, scope, isElement);
        return inner.endsWith('?') ? inner : `${inner}?`;
      }
      case 'array':
        return `[${this.typeOf(d.element, key, scope, true)}]`;
      case 'record': {
        if (def(d.keyType).type !== 'string')
          throw new Error(`${key}: record keys must be strings`);
        return `[String: ${this.typeOf(d.valueType, key, scope)}]`;
      }
      case 'unknown':
      case 'any':
        return 'JSONValue';
      case 'enum': {
        const name = this.nestedName(scope, key, isElement);
        scope.nested.push(this.stringEnum(name, Object.values(d.entries) as string[]));
        return name;
      }
      case 'object': {
        const name = this.nestedName(scope, key, isElement);
        const inner: Scope = { nested: [], nestedNames: new Set(), root: scope.root };
        const fields = this.fields(d.shape, inner);
        scope.nested.push(this.structSource(name, fields, inner, []));
        return name;
      }
      case 'union':
        throw new Error(`${key}: nested unions are not supported; register the schema as a root`);
      default:
        throw new Error(`${key}: unsupported schema type ${d.type}`);
    }
  }
}

export function emitSwift(entries: readonly ContractEntry[]): Map<string, string> {
  return new SwiftEmitter(entries).emit();
}

export interface CheckResult {
  missing: string[];
  stale: string[];
  changed: string[];
}

/** Compare emitted files with what a directory holds (`--check`). */
export function compareWithDirectory(
  emitted: Map<string, string>,
  existing: Map<string, string>,
): CheckResult {
  const missing = [...emitted.keys()].filter((f) => !existing.has(f)).sort();
  const stale = [...existing.keys()].filter((f) => !emitted.has(f)).sort();
  const changed = [...emitted.keys()]
    .filter((f) => existing.has(f) && existing.get(f) !== emitted.get(f))
    .sort();
  return { missing, stale, changed };
}
